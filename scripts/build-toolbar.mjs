import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const modulesDir = path.join(root, "src/toolbar/modules");
const order = fs
  .readdirSync(modulesDir)
  .filter((name) => /^\d+-.*\.js$/.test(name) && !name.startsWith("00-") && !name.startsWith("01-"))
  .sort();

const body = order
  .map((name) => `// ---- ${name} ----\n${fs.readFileSync(path.join(modulesDir, name), "utf8")}`)
  .join("\n\n");

const output = `// AUTO-GENERATED by scripts/build-toolbar.mjs. Do not edit.
// Text Selection Toolbar, scoped inside its own Shadow DOM.

export function installTextSelectionToolbar({
  getValue,
  setValue,
  openSettings,
  translateSelection,
  detectLanguage,
  countScriptChars,
}) {
  const safeGetValue = getValue;
  const safeSetValue = setValue;
  const __kissOpenSettings = openSettings;

  const safeOpenTab = (url, options) => {
    if (typeof GM !== "undefined" && GM.openInTab) {
      GM.openInTab(url, options);
    } else if (typeof GM_openInTab === "function") {
      GM_openInTab(url, options);
    } else {
      window.open(url, "_blank", "noopener");
    }
  };

  function requestTranslation(text, rect) {
    if (typeof translateSelection === "function") translateSelection(text, rect);
  }

${body}
}
`;

fs.writeFileSync(path.join(root, "src/toolbar/generated.js"), output);
console.log(`Generated src/toolbar/generated.js from ${order.length} modules.`);
